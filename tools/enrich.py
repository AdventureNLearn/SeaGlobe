#!/usr/bin/env python3
"""v2.2 content pass: merge history, story, facts and citations into the route files.

Additive only. Route records gain `history`, `story`, `facts`, `content_citations`;
named voyages gain a `vessel` object; vehicle types go to web/data/content.js
(window.SEAGLOBE_DATA.vehicle_info). Sources: tools/content_routes.py and
tools/content_assets.py. Run after tools/build_routes.py (build_routes calls it).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
ROOT = HERE.parent
FAM = ROOT / "web" / "data" / "routes"


def write_js(name, key, obj, path, gen="tools/enrich.py"):
    body = json.dumps(obj, ensure_ascii=False, indent=1)
    path.write_text(f"/* Generated by {gen} from {name}. Do not edit by hand. */\n"
                    f"(window.SEAGLOBE_DATA = window.SEAGLOBE_DATA || {{}})[{json.dumps(key)}] = {body};\n", encoding="utf-8")


def main():
    from content_routes import R
    from content_assets import V, VESSELS
    seen, vseen = set(), set()
    for f in sorted(FAM.glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        for r in d["routes"]:
            c = R.get(r["id"])
            if not c:
                raise SystemExit(f"no content for route {r['id']}")
            r.update({k: c[k] for k in ("history", "story", "facts", "content_citations")})
            seen.add(r["id"])
            for vo in r.get("schedule", {}).get("voyages", []):
                if vo.get("id") in VESSELS:
                    vo["vessel"] = VESSELS[vo["id"]]
                    vseen.add(vo["id"])
        f.write_text(json.dumps(d, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        write_js(f"web/data/routes/{f.name}", f"routes:{d['family']}", d, f.with_suffix(".js"), "tools/build_routes.py + tools/enrich.py")
    if set(R) - seen:
        raise SystemExit(f"content for unknown routes: {sorted(set(R) - seen)}")
    if set(VESSELS) - vseen:
        raise SystemExit(f"vessel content for unknown voyages: {sorted(set(VESSELS) - vseen)}")
    out = ROOT / "web" / "data" / "content.js"
    out.write_text("/* Generated by tools/enrich.py from tools/content_assets.py: history, story and facts for each vehicle type.\n"
                   "   Every fact is cited; gaps are marked [UNKNOWN]. */\n"
                   "(window.SEAGLOBE_DATA = window.SEAGLOBE_DATA || {}).vehicle_info = "
                   + json.dumps(V, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print(f"enriched {len(seen)} routes, {len(vseen)} named vessels, {len(V)} vehicle types")


if __name__ == "__main__":
    main()
