#!/usr/bin/env python3
"""Fill bytes and sha256 in the asset manifest and write web/data/assets.js and web/assets.json.
Repo paths are looked up under web/ first, then the repository root (walkthrough/ lives at the root and is
copied to the site root by tools/assemble_pages.sh). Large-tier R2 files are read from the staging folder
(--staging, default ../seaglobe-build/r2-staging); if it is missing, existing values are kept."""
import argparse, hashlib, json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""): h.update(b)
    return h.hexdigest()

def find(rel):
    for base in (os.path.join(ROOT, "web"), ROOT):
        p = os.path.join(base, rel)
        if os.path.exists(p): return p
    return None

def dir_info(p):
    n = b = 0
    for d, _, fs in os.walk(p):
        for f in fs: n += 1; b += os.path.getsize(os.path.join(d, f))
    return n, b

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--staging", default=os.path.join(os.path.dirname(ROOT), "seaglobe-build", "r2-staging"))
    a = ap.parse_args()
    man = json.load(open(os.path.join(ROOT, "data", "assets.json")))
    version = open(os.path.join(ROOT, "VERSION")).read().strip()
    old = {}
    try:
        old = {x["id"]: x for x in json.load(open(os.path.join(ROOT, "web", "assets.json")))["assets"]}
    except Exception:
        pass
    out, missing = [], []
    for x in man["assets"]:
        y = {k: v for k, v in x.items() if k != "staged"}
        if x.get("path"):
            p = find(x["path"])
            if not p: missing.append(x["path"])
            elif os.path.isdir(p): y["files"], y["bytes"] = dir_info(p)
            else: y["bytes"], y["sha256"] = os.path.getsize(p), sha(p)
        if x.get("fallback"):
            p = find(x["fallback"])
            if p: y["fallback_bytes"], y["fallback_sha256"] = os.path.getsize(p), sha(p)
            else: missing.append(x["fallback"])
        if x.get("staged"):
            p = os.path.join(a.staging, x["staged"])
            if os.path.exists(p): y["bytes"], y["sha256"] = os.path.getsize(p), sha(p)
            elif x["id"] in old:
                for k in ("bytes", "sha256"):
                    if k in old[x["id"]]: y[k] = old[x["id"]][k]
        out.append(y)
    doc = {"version": version, "assets": out}
    js = "/* Generated by tools/build_assets.py from data/assets.json. Do not edit by hand. */\nwindow.SEAGLOBE_ASSETS = " + json.dumps(doc, ensure_ascii=False, separators=(",", ":")) + ";\n"
    open(os.path.join(ROOT, "web", "data", "assets.js"), "w").write(js)
    json.dump(doc, open(os.path.join(ROOT, "web", "assets.json"), "w"), ensure_ascii=False, indent=1)
    if missing:
        print("missing files:", ", ".join(missing), file=sys.stderr); sys.exit(1)
    print("assets:", len(out), "written")

if __name__ == "__main__":
    main()
