"""Build the drill-down region packs (world > country > state/province > county > town) from Natural Earth
(public domain). Build time only; the app reads the generated web/data/regions/*.js files, never the network.

Usage: python3 tools/build_regions.py <folder with the Natural Earth GeoJSON downloads>
  ne_110m_admin_0_countries.geojson, ne_50m_admin_1_states_provinces.geojson,
  ne_10m_admin_2_counties.geojson (US counties), ne_10m_populated_places_simple.geojson
from https://github.com/nvkelso/natural-earth-vector (geojson/), downloaded 2026-11-14.
Coordinates are rounded (2 decimals for countries, 3 below) and rings with fewer than 4 points are dropped.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "web" / "data" / "regions"
SRC = "Natural Earth (public domain), naturalearthdata.com"


def rnd(geom, nd):
    def ring(r):
        out = []
        for x, y in r:
            p = [round(x, nd), round(y, nd)]
            if not out or out[-1] != p:
                out.append(p)
        return out if len(out) >= 4 else None
    polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
    res = []
    for poly in polys:
        rings = [q for q in (ring(r) for r in poly) if q]
        if rings:
            res.append(rings)
    return res


def bbox(polys):
    xs = [p[0] for poly in polys for r in poly for p in r]
    ys = [p[1] for poly in polys for r in poly for p in r]
    return [round(min(xs), 2), round(min(ys), 2), round(max(xs), 2), round(max(ys), 2)] if xs else None


def write(key, obj):
    path = OUT / (key + ".js")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("/* Generated by tools/build_regions.py from Natural Earth (public domain). Do not edit by hand. */\n"
                    "(window.SEAGLOBE_REGIONS = window.SEAGLOBE_REGIONS || {})[" + json.dumps(key) + "] = "
                    + json.dumps(obj, separators=(",", ":"), ensure_ascii=False) + ";\n")
    return path.stat().st_size


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def main(src):
    src = pathlib.Path(src)
    load = lambda n: json.load(open(src / (n + ".geojson")))
    index = {"source": SRC, "levels": ["world", "country", "state", "county", "town"], "regions": []}
    countries = []
    for f in load("ne_110m_admin_0_countries")["features"]:
        p = f["properties"]
        a3 = p["ADM0_A3"]
        polys = rnd(f["geometry"], 2)
        rid = "country-" + a3.lower()
        countries.append({"id": rid, "a3": a3, "name": p["NAME"], "polys": polys})
        index["regions"].append({"id": rid, "level": "country", "name": p["NAME"], "long": p["NAME_LONG"], "a3": a3,
                                 "iso_a2": p["ISO_A2"], "parent": "world", "bbox": bbox(polys), "continent": p["CONTINENT"]})
    sizes = {"world": write("world", {"countries": countries})}
    by_country = {}
    for f in load("ne_50m_admin_1_states_provinces")["features"]:
        p = f["properties"]
        a3 = p["adm0_a3"]
        rid = "state-" + slug(p["iso_3166_2"] or p["adm1_code"])
        polys = rnd(f["geometry"], 3)
        by_country.setdefault(a3, []).append({"id": rid, "name": p["name"], "iso": p["iso_3166_2"], "polys": polys})
        index["regions"].append({"id": rid, "level": "state", "name": p["name"], "type": p["type_en"], "iso": p["iso_3166_2"],
                                 "postal": p["postal"], "parent": "country-" + a3.lower(), "bbox": bbox(polys)})
    for a3, items in by_country.items():
        sizes["admin1/" + a3] = write("admin1/" + a3, {"country": a3, "states": items})
    by_state = {}
    for f in load("ne_10m_admin_2_counties")["features"]:
        p = f["properties"]
        st = p["REGION"]  # postal code, e.g. MI
        iso = "US-" + st
        rid = "county-us-" + str(p["CODE_LOCAL"] or p["FIPS"]).lower()
        polys = rnd(f["geometry"], 3)
        by_state.setdefault(st, []).append({"id": rid, "name": p["NAME"], "fips": p["CODE_LOCAL"], "polys": polys})
        index["regions"].append({"id": rid, "level": "county", "name": p["NAME"], "type": p["TYPE_EN"], "fips": p["CODE_LOCAL"],
                                 "parent": "state-" + slug(iso), "bbox": bbox(polys)})
    for st, items in by_state.items():
        sizes["counties/US-" + st] = write("counties/US-" + st, {"state": "US-" + st, "counties": items})
    towns = {}
    for f in load("ne_10m_populated_places_simple")["features"]:
        p = f["properties"]
        towns.setdefault(p["adm0_a3"], []).append({"name": p["name"], "adm1": p["adm1name"], "lat": round(p["latitude"], 3),
                                                   "lon": round(p["longitude"], 3), "kind": p["featurecla"], "pop": p["pop_max"]})
    for a3, items in towns.items():
        items.sort(key=lambda t: -(t["pop"] or 0))
        sizes["towns/" + a3] = write("towns/" + a3, {"country": a3, "towns": items})
    index["packs"] = sorted(sizes)
    sizes["index"] = write("index", index)
    total = sum(sizes.values())
    print(f"{len(index['regions'])} regions, {len(sizes)} files, {total/1e6:.2f} MB, largest "
          + ", ".join(f"{k} {v/1e3:.0f} kB" for k, v in sorted(sizes.items(), key=lambda kv: -kv[1])[:4]))


if __name__ == "__main__":
    main(sys.argv[1])
