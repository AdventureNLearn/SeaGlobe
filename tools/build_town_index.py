#!/usr/bin/env python3
"""One small file listing every town label in web/data/regions/towns/*.js, so the encyclopedia and the chat can
index all towns without loading 225 packs. Built only from those generated packs (Natural Earth, public domain).
Output: web/data/regions/towns-index.js  (rows: [name, country a3, admin-1 name or null, lat, lon, kind, population])"""
import glob, json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "web", "data", "regions")
rows = []
for f in sorted(glob.glob(os.path.join(D, "towns", "*.js"))):
    t = open(f, encoding="utf-8").read()
    obj = json.loads(t[t.index("] = ") + 4:].rstrip().rstrip(";"))
    for x in obj["towns"]:
        rows.append([x["name"], obj["country"], x.get("adm1"), x["lat"], x["lon"], x.get("kind"), x.get("pop")])
out = ("/* Generated by tools/build_town_index.py from web/data/regions/towns/*.js (Natural Earth, public domain). Do not edit by hand. */\n"
       '(window.SEAGLOBE_REGIONS = window.SEAGLOBE_REGIONS || {})["towns-index"] = '
       + json.dumps({"source": "Natural Earth (public domain), naturalearthdata.com", "fields": ["name", "a3", "adm1", "lat", "lon", "kind", "pop"], "towns": rows}, ensure_ascii=False, separators=(",", ":")) + ";\n")
open(os.path.join(D, "towns-index.js"), "w", encoding="utf-8").write(out)
print("towns-index:", len(rows), "towns,", round(len(out.encode()) / 1024), "KiB")
