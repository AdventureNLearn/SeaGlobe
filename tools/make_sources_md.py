"""Write SOURCES.md: every bundled route record -> its citations, timing kind and confidence.

Run after tools/build_routes.py.  python tools/make_sources_md.py
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FAM = ROOT / "web" / "data" / "routes"


def load():
    out = []
    for f in sorted(FAM.glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        for r in d["routes"]:
            out.append((f.stem, d.get("title", f.stem), r))
    return out



def uap_lines():
    path = ROOT / "web" / "data" / "next" / "uap" / "uap.json"
    if not path.is_file():
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    recs = [r for r in (data.get("records") or []) if isinstance(r, dict) and r.get("example") is not True]
    if not recs:
        return []
    lines = ["", "## Official UAP records (declassified) (`web/data/next/uap/uap.json`)", "",
             "Official U.S. government records. Primary sources only. Pin coordinates come from OurAirports (public domain) and are recorded on each record, not listed as a primary citation here.", ""]
    for r in recs:
        lines.append(f"### {r.get('title', '[UNKNOWN]')} (`{r.get('id', '')}`)")
        bits = ["official record"]
        if r.get("date"):
            bits.append(str(r["date"]))
        if r.get("agency"):
            bits.append(str(r["agency"]))
        if r.get("claim"):
            bits.append(f"claim `{r['claim']}`")
        lines.append("- " + " · ".join(bits))
        for c in r.get("citations") or []:
            if not isinstance(c, str) or not c.strip():
                continue
            if "secondary" in c.lower():
                continue
            lines.append(f"- {c}")
        lines.append("")
    return lines


def main():
    recs = load()
    kinds = Counter(r["schedule"]["kind"] for _, _, r in recs)
    recon = sum(1 for *_, r in recs if r.get("reconstruction"))
    lines = ["# SOURCES", "",
             "Generated by `tools/make_sources_md.py` from `web/data/routes/*.json` and official UAP records in `web/data/next/uap/uap.json`. Do not edit by hand.", "",
             f"{len(recs)} records in {len({f for f, _, _ in recs})} family files. "
             f"Reconstructed: {recon}. Not marked reconstruction: {len(recs) - recon}.", "",
             f"Timing: dated (real dates) {kinds['dated']}, years (published years, reconstructed months/pace) {kinds['years']}, "
             f"traffic (illustrative, reconstructed timing) {kinds['traffic']}.", "",
             "| Family | Records | Reconstructed |", "|---|---:|---:|"]
    fam = Counter(f for f, _, _ in recs)
    famr = Counter(f for f, _, r in recs if r.get("reconstruction"))
    for f in sorted(fam):
        lines.append(f"| {f} | {fam[f]} | {famr[f]} |")
    lines.append("")
    cur = None
    for f, title, r in recs:
        if f != cur:
            cur = f
            lines += ["", f"## {title} (`data/routes/{f}.json`)", ""]
        flag = "reconstruction" if r.get("reconstruction") else "dataset/record"
        lines.append(f"### {r['name']} (`{r['id']}`)")
        lines.append(f"- {r['type']} · {r['era']} · vehicle `{r['vehicle']}` · timing **{r['schedule']['kind']}** · {flag} · confidence {r.get('confidence_level')}")
        if r.get("derived_from"):
            lines.append(f"- derived from: {r['derived_from'] if isinstance(r['derived_from'], str) else ', '.join(map(str, r['derived_from']))}")
        for c in r.get("citations", []):
            lines.append(f"- {c}")
        lines.append("")
    lines.extend(uap_lines())
    (ROOT / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("SOURCES.md:", len(recs), "records", dict(kinds), "reconstructed", recon)


if __name__ == "__main__":
    main()
