#!/usr/bin/env python3
"""Wrap the official three.js 0.187.0 ES-module build as one classic script.

Input: an npm copy of three@0.187.0 (build/three.core.js + build/three.module.js).
Output: web/vendor/three.global.js, which sets window.THREE.
No code is changed except the import/export lines, which become plain object
wiring, so the page works as a static site and from a single HTML file.
Usage: python3 tools/vendor_three.py <path-to-node_modules/three>
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "web" / "vendor" / "three.global.js"


def names(spec):
    out = []
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        m = re.fullmatch(r"([\w$]+)(?:\s+as\s+([\w$]+))?", part)
        if not m:
            raise SystemExit("cannot parse export part: " + part)
        out.append((m.group(1), m.group(2) or m.group(1)))
    return out


def main():
    src = Path(sys.argv[1]) / "build"
    core = (src / "three.core.js").read_text(encoding="utf-8")
    mod = (src / "three.module.js").read_text(encoding="utf-8")
    pkg = (src.parent / "package.json").read_text(encoding="utf-8")
    if '"version": "0.187.0"' not in pkg:
        raise SystemExit("expected three 0.187.0")

    core_exp = re.findall(r"^export \{([^}]*)\};\s*$", core, re.M)
    assert len(core_exp) == 1, "core export"
    core_body = re.sub(r"^export \{[^}]*\};\s*$", "", core, flags=re.M)
    core_ret = ", ".join(f"{alias}: {local}" for local, alias in names(core_exp[0]))

    imp = re.findall(r"^import \{([^}]*)\} from './three.core.js';\s*$", mod, re.M)
    reexp = re.findall(r"^export \{([^}]*)\} from './three.core.js';\s*$", mod, re.M)
    own = re.findall(r"^export \{([^}]*)\};\s*$", mod, re.M)
    assert len(imp) == 1 and len(reexp) == 1 and len(own) == 1, "module shape"
    mod_body = re.sub(r"^(import|export) \{[^}]*\}( from '[^']*')?;\s*$", "", mod, flags=re.M)
    assert "import " not in "".join(l for l in mod_body.splitlines() if l.startswith("import ")), "stray import"
    destructure = ", ".join(f"{local}: {alias}" if local != alias else local for local, alias in names(imp[0]))
    mod_ret = ", ".join(f"{alias}: {local}" for local, alias in names(own[0]))
    re_ret = ", ".join(f"{alias}: __core.{local}" for local, alias in names(reexp[0]))

    out = (
        "/* three.js r187 (0.187.0), MIT License, Copyright 2010-2026 Three.js Authors.\n"
        "   Classic-script wrapper generated by tools/vendor_three.py from the official\n"
        "   build/three.core.js and build/three.module.js. Sets window.THREE. */\n"
        "(function (root) {\n'use strict';\n"
        "const __core = (function () {\n" + core_body + "\nreturn { " + core_ret + " };\n})();\n"
        "const __mod = (function () {\nconst { " + destructure + " } = __core;\n" + mod_body +
        "\nreturn { " + mod_ret + " };\n})();\n"
        "root.SEAGLOBE_THREE = Object.freeze(Object.assign({ " + re_ret + " }, __mod));\n"
        "})(typeof window !== 'undefined' ? window : globalThis);\n"
    )
    OUT.write_text(out, encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT), len(out), "bytes")


if __name__ == "__main__":
    main()
