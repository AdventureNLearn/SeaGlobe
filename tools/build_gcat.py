"""Slice Jonathan McDowell's GCAT (CC BY 4.0) into the small files SeaGlobe hosts.

Usage: python3 tools/build_gcat.py <folder with satcat.tsv, launchlog.tsv, sites.tsv>
  from https://planet4589.org/space/gcat/tsv/ (cat/satcat.tsv, derived/launchlog.tsv, tables/sites.tsv), 2026-11-14.
Writes data/sources/gcat/*.csv (the hosted slice) and web/data/space/gcat.js (what the app loads).
Only fields whose meaning the GCAT documentation states are used: SatType byte 1 = coarse type (P = payload),
LDate = launch date, Perigee/Apogee/Inc as listed, the orbital launch log's Launch_Tag/Launch_Date/Launch_Site,
and the sites table's names and coordinates. The full catalogue is a large-tier asset (R2), not in the repo.
"""
import csv, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
CITE = "Data from GCAT (J. McDowell, planet4589.org/space/gcat), CC BY 4.0; release 1.8.9, data update 2026 Nov 13; read 14 Nov 2026"
NOTABLE = ["S00002", "S00004", "S00340", "S00858", "S01954", "S04039", "S05160", "S06126", "S06633", "S10684", "S20580",
           "S25544", "S37820", "S48274"]


def table(path):
    with open(path, encoding="utf-8") as f:
        head = f.readline().lstrip("#").rstrip("\n").split("\t")
        return [dict(zip(head, [c.strip() for c in r])) for r in csv.reader(f, delimiter="\t") if r and not r[0].startswith("#")]


def year(d):
    m = re.match(r"(\d{4})", d or "")
    return int(m.group(1)) if m else None


def num(s):
    try:
        return float(s.replace("?", ""))
    except ValueError:
        return None


def main(src):
    src = pathlib.Path(src)
    sat = table(src / "satcat.tsv")
    log = table(src / "launchlog.tsv")
    sites = {s["Site"]: s for s in table(src / "sites.tsv")}
    payloads = {}
    for r in sat:
        y = year(r["LDate"])
        if y and r["Type"][:1] == "P" and r["Primary"] == "Earth":
            payloads[y] = payloads.get(y, 0) + 1
    launches, by_site = {}, {}
    seen = set()
    for r in log:
        tag = r["Launch_Tag"]
        if tag in seen:
            continue
        seen.add(tag)
        y = year(r["Launch_Date"])
        if not y:
            continue
        launches[y] = launches.get(y, 0) + 1
        s = by_site.setdefault(r["Launch_Site"], {"count": 0, "first": y, "last": y})
        s["count"] += 1; s["first"] = min(s["first"], y); s["last"] = max(s["last"], y)
    site_rows = []
    for code, s in sorted(by_site.items(), key=lambda kv: -kv[1]["count"]):
        t = sites.get(code)
        if not t:
            continue
        lat, lon = num(t["Latitude"]), num(t["Longitude"])
        if lat is None or lon is None:
            continue
        site_rows.append({"code": code, "name": t["Name"], "short": t["ShortName"], "state": t["StateCode"], "location": t["Location"],
                          "lat": round(lat, 3), "lon": round(lon, 3), "launches": s["count"], "first": s["first"], "last": s["last"]})
    by_j = {r["JCAT"]: r for r in sat}
    craft = []
    for j in NOTABLE:
        r = by_j[j]
        craft.append({"jcat": j, "name": r["Name"], "plname": r["PLName"], "ldate": r["LDate"], "owner": r["Owner"], "state": r["State"],
                      "perigee_km": num(r["Perigee"]), "apogee_km": num(r["Apogee"]), "inc_deg": num(r["Inc"]), "orbit": r["OpOrbit"]})
    out = ROOT / "data" / "sources" / "gcat"
    out.mkdir(parents=True, exist_ok=True)
    with open(out / "counts-by-year.csv", "w", newline="") as f:
        w = csv.writer(f); w.writerow(["year", "earth_payloads_catalogued_by_launch_year", "orbital_launches_in_launch_log"])
        for y in range(1957, max(payloads) + 1):
            w.writerow([y, payloads.get(y, 0), launches.get(y, 0)])
    with open(out / "launch-sites.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(site_rows[0])); w.writeheader(); w.writerows(site_rows)
    with open(out / "notable-objects.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(craft[0])); w.writeheader(); w.writerows(craft)
    data = {"citation": CITE, "licence": "CC BY 4.0",
            "years": {str(y): payloads.get(y, 0) for y in range(1957, max(payloads) + 1)},
            "launches": {str(y): launches.get(y, 0) for y in range(1957, max(launches) + 1)},
            "sites": site_rows, "craft": craft}
    p = ROOT / "web" / "data" / "space" / "gcat.js"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("/* Generated by tools/build_gcat.py. " + CITE + ". Do not edit by hand. */\n"
                 "(window.SEAGLOBE_DATA = window.SEAGLOBE_DATA || {}).gcat = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n")
    print(f"payload years {len(payloads)}, launches {sum(launches.values())}, sites {len(site_rows)}, craft {len(craft)}, gcat.js {p.stat().st_size/1e3:.0f} kB")


if __name__ == "__main__":
    main(sys.argv[1])
