// Write walkthrough/CAPTIONS.md from the video scripts (segment durations + caption timings).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const strip = (h) => h.replace(/<[^>]+>/g, "").replace(/&amp;/g, "&");
const fmt = (t) => { const m = Math.floor(t / 60), s = t - m * 60; return m + ":" + s.toFixed(1).padStart(4, "0"); };
let out = "# Video captions\n\nGenerated by `tools/video/captions_md.mjs` from the video scripts. No music or narration; captions are burned into the video.\n";
// The air walkthrough has a phone part (tools/video/air_phone.mjs, captions burned in by air_join.sh) between its two scripts.
const PHONE = { dur: 22, caps: [[0, 3, "Phone layout (390 × 844, touch) · the v2.2.1 phone layout keeps working with the air layer"], [3, 8.5, "Menu sheet: eras, layers, routes"], [8.5, 22, "Tap a 747: its card opens as a bottom sheet with the reconstruction label and citations"]] };
for (const [files, mp4, title] of [[["atlas.mjs"], "atlas-walkthrough.mp4", "Full walkthrough"], [["ships.mjs"], "seaglobe-ships.mp4", "Ships demo"], [["air.mjs", PHONE, "air_end.mjs"], "air-layer-walkthrough.mp4", "Air layer walkthrough"]]) {
  let t0 = 0;
  out += `\n## ${title} — walkthrough/${mp4}\n\n| Time | Segment | Caption |\n|---|---|---|\n`;
  for (const file of files) {
  if (typeof file !== "string") { for (const c of file.caps) out += `| ${fmt(t0 + c[0])}–${fmt(t0 + c[1])} | phone | ${c[2]} |\n`; t0 += file.dur; continue; }
  const src = fs.readFileSync(path.join(here, file), "utf8");
  const parts = src.split("seg.push(").slice(1);
  for (const p of parts) {
    const name = /name: "([^"]+)"/.exec(p)[1], dur = Number(/dur: ([0-9.]+)/.exec(p)[1]);
    const caps = [...p.matchAll(/\[\s*([0-9.]+),\s*([0-9.]+),\s*"((?:[^"\\]|\\.)*)"\s*\]/g)];
    if (!caps.length) out += `| ${fmt(t0)} | ${name} | ${/titleHTML/.test(p) ? "Title card: SEAGLOBE · World Trade Route Atlas · 500 BCE – today" : /creditsHTML/.test(p) ? "Credits and sources card" : /eraCardHTML/.test(p) ? "Era card (AI-generated artistic impression)" : /title\("SeaGlobe v2\.3/.test(p) ? "Title card: SeaGlobe v2.3 · The air layer, 1903 – today" : /About this build/.test(p) ? "Notes card: assumptions (height, speed, models, sources, [UNKNOWN] gaps)" : "—"} |\n`;
    for (const c of caps) out += `| ${fmt(t0 + Number(c[1]))}–${fmt(t0 + Number(c[2]))} | ${name} | ${strip(c[3])} |\n`;
    t0 += dur;
  }
  }
  out += `\nTotal: ${fmt(t0)}\n`;
}
fs.writeFileSync(path.join(here, "..", "..", "walkthrough", "CAPTIONS.md"), out);
console.log("wrote walkthrough/CAPTIONS.md");
