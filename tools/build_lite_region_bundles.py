# US Census regions, plus PR and VI with the South.
COUNTY_GROUPS = {
    "west": "AK HI WA OR CA NV ID MT WY UT CO AZ NM".split(),
    "south": "TX OK AR LA KY TN MS AL WV VA NC SC GA FL MD DE DC PR VI".split(),
    "midwest": "ND SD NE KS MN IA MO WI IL MI IN OH".split(),
    "northeast": "ME NH VT MA RI CT NY NJ PA".split(),
}


def extract(path: Path) -> tuple[str, str]:
    text = path.read_text(encoding="utf-8")
    m = ASSIGN.search(text)
    if not m:
        raise SystemExit(f"cannot parse pack assignment in {path}")
    raw = text[m.end():].strip()
    if raw.endswith(";"):
        raw = raw[:-1].strip()
    json.loads(raw)
    return m.group(1), raw


def load_index_continents() -> dict[str, str]:
    text = (REGIONS / "index.js").read_text(encoding="utf-8")
    m = ASSIGN.search(text)
    if not m:
        raise SystemExit("cannot parse web/data/regions/index.js")
    raw = text[m.end():].strip()
    if raw.endswith(";"):
        raw = raw[:-1].strip()
    idx = json.loads(raw)
    out = {}
    for row in idx.get("regions") or []:
        if row.get("level") == "country" and row.get("a3"):
            out[row["a3"]] = row.get("continent") or "other"
    return out


def slug_for_continent(name: str) -> str:
    return CONTINENT_SLUG.get(name, "other")


def packs_in(folder: Path) -> list[Path]:
    return sorted(p for p in folder.glob("*.js") if p.is_file())


def group_country_packs(kind: str, continents: dict[str, str]) -> dict[str, list[tuple[str, str]]]:
    groups: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for path in packs_in(REGIONS / kind):
        key, raw = extract(path)
        stem = path.stem
        if kind == "admin1" and stem == "rest":
            bundle = "admin1-rest"
        else:
            continent = continents.get(stem) or TOWN_CONTINENT.get(stem)
            if not continent:
                raise SystemExit(f"no continent mapping for {kind}/{stem}")
            bundle = f"{kind}-{slug_for_continent(continent)}"
        groups[bundle].append((key, raw))
    for items in groups.values():
        items.sort(key=lambda kv: kv[0])
    return groups


def group_county_packs() -> dict[str, list[tuple[str, str]]]:
    assigned = {}
    for group, states in COUNTY_GROUPS.items():
        for st in states:
            assigned[f"US-{st}"] = f"counties-{group}"
    groups: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for path in packs_in(REGIONS / "counties"):
        bundle = assigned.get(path.stem)
        if not bundle:
            raise SystemExit(f"no county group for {path.name}")
        key, raw = extract(path)
        groups[bundle].append((key, raw))
    for items in groups.values():
        items.sort(key=lambda kv: kv[0])
    return groups


def render_bundle(bundle_id: str, kind: str, items: list[tuple[str, str]]) -> str:
    lines = [HEADER.format(kind=kind),
             f'(window.SEAGLOBE_REGION_BUNDLES = window.SEAGLOBE_REGION_BUNDLES || {{}})[{json.dumps(bundle_id)}] = {{\n']
    last = len(items) - 1
    for i, (key, raw) in enumerate(items):
        comma = "," if i < last else ""
        lines.append(f" {json.dumps(key)}: {raw}{comma}\n")
    lines.append("};\n")
    return "".join(lines)


def render_map(mapping: dict[str, str]) -> str:
    body = json.dumps(mapping, indent=1, sort_keys=True, ensure_ascii=False)
    return (
        "/* Generated by tools/build_lite_region_bundles.py. Do not edit by hand. */\n"
        "window.SEAGLOBE_LITE_REGION_MAP = " + body + ";\n"
    )


def build() -> dict[str, str]:
    continents = load_index_continents()
    files: dict[str, str] = {}
    mapping: dict[str, str] = {}
    groups = {}
    groups.update(group_country_packs("towns", continents))
    groups.update(group_country_packs("admin1", continents))
    groups.update(group_county_packs())
    for bundle_id, items in sorted(groups.items()):
        kind = bundle_id.split("-", 1)[0]
        text = render_bundle(bundle_id, kind, items)
        size = len(text.encode("utf-8"))
        if size > LIMIT:
            raise SystemExit(f"{bundle_id}.js is {size} bytes, over the {LIMIT} byte lite file cap")
        files[bundle_id + ".js"] = text
        for key, _ in items:
            if key in mapping:
                raise SystemExit(f"{key} mapped twice ({mapping[key]} and {bundle_id})")
            mapping[key] = bundle_id
    files["map.js"] = render_map(mapping)
    return files


def write(files: dict[str, str]) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    keep = set(files)
    for existing in OUT.glob("*.js"):
        if existing.name not in keep:
            existing.unlink()
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = build()
    if args.check:
        bad = []
        on_disk = {p.name for p in OUT.glob("*.js")}
        if on_disk != set(files):
            bad.append("bundle file list differs: " + ", ".join(sorted(on_disk ^ set(files))))
        for name, text in files.items():
            path = OUT / name
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                bad.append(name)
        if bad:
            print("lite region bundles are out of date; run tools/build_lite_region_bundles.py", file=sys.stderr)
            print("  " + "\n  ".join(bad), file=sys.stderr)
            sys.exit(1)
        print("lite region bundles up to date:", len(files) - 1, "bundles + map")
        return
    write(files)
    sizes = sorted(((len(text.encode("utf-8")), name) for name, text in files.items()), reverse=True)
    total = sum(s for s, _ in sizes)
    n_bundles = len(files) - 1
    print(f"lite region bundles: {n_bundles} bundles + map, {total / 1048576:.2f} MiB")
    for size, name in sizes:
        print(f"  {size / 1048576:.3f} MiB  {name}")


if __name__ == "__main__":
    main()
