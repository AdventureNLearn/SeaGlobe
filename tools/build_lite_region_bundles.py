#!/usr/bin/env python3
"""Pack per-country region files into a handful of lite-only bundles, grouped by world region.

Desktop and phone still load web/data/regions/{towns,admin1,counties}/*.js one country (or
US state) at a time. The lite edition (SEAGLOBE_EDITION.lite) loads one bundle per group and
pulls out the selected country. Bundles are rebuilt from those source files, so the data in
each pack is identical.

Usage:
  python3 tools/build_lite_region_bundles.py
  python3 tools/build_lite_region_bundles.py --check   # fail if committed bundles are stale
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGIONS = ROOT / "web" / "data" / "regions"
OUT = REGIONS / "lite-bundles"
LIMIT = 5 * 1024 * 1024  # same per-file cap as grokme/lite-manifest.json
HEADER = (
    "/* Generated by tools/build_lite_region_bundles.py from web/data/regions/{kind} "
    "(Natural Earth, public domain). Do not edit by hand. */\n"
)
ASSIGN = re.compile(r'\)\["([^"]+)"\]\s*=\s*', re.S)

