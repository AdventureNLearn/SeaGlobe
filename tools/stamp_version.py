"""Write web/version.json and web/js/version.js from VERSION (and, at release time, the commit and zip hash).

Usage:
  python3 tools/stamp_version.py                       # local build: commit "[set at release]"
  python3 tools/stamp_version.py --commit <sha> [--zip-sha256 <hex> --download-url <url>]   # release (make_release.sh)
version.json is what every copy compares itself with (read-only fetch from the public Pages site).
"""
import argparse, datetime, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SITE = "https://adventurenlearn.github.io/SeaGlobe/"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--commit", default="[set at release]")
    ap.add_argument("--date", default=datetime.date.today().isoformat())
    ap.add_argument("--zip-sha256", default="")
    ap.add_argument("--download-url", default="")
    ap.add_argument("--out-dir", default="", help="write only version.json into this folder (release); leave the tree alone")
    a = ap.parse_args()
    version = (ROOT / "VERSION").read_text().strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?", version):
        raise SystemExit("VERSION is not semver: " + version)
    data = {
        "name": "SeaGlobe",
        "version": version,
        "commit": a.commit,
        "date": a.date,
        "changelog": "CHANGELOG.md",
        "changelog_url": SITE + "CHANGELOG.md",
        "latest_url": SITE + "version.json",
        "download_url": a.download_url or "[set at release]",
        "zip_sha256": a.zip_sha256 or "[set at release]",
    }
    if a.out_dir:
        out = pathlib.Path(a.out_dir); out.mkdir(parents=True, exist_ok=True)
        (out / "version.json").write_text(json.dumps(data, indent=1) + "\n")
        print("wrote", out / "version.json", "version", version, "commit", a.commit)
        return
    (ROOT / "web" / "version.json").write_text(json.dumps(data, indent=1) + "\n")
    (ROOT / "web" / "js" / "version.js").write_text(
        "/* Generated by tools/stamp_version.py. The version this copy runs; compared with the published version.json. */\n"
        "window.SEAGLOBE_VERSION = " + json.dumps(data, indent=1) + ";\n")
    print("version", version, "commit", a.commit)


if __name__ == "__main__":
    main()
