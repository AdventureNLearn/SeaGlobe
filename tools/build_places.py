"""Air hub places for the encyclopedia and the Air hubs layer, from the OurAirports slice (public domain).
Usage: python3 tools/build_places.py   (reads data/sources/ourairports/airports-slice.csv, writes web/data/places/airports.js)"""
import csv, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]


def main():
    rows = []
    with open(ROOT / "data" / "sources" / "ourairports" / "airports-slice.csv", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["name"].startswith("(Duplicate)"):   # OurAirports marks superseded duplicate records this way
                continue
            rows.append([r["ident"], r["name"], round(float(r["latitude_deg"]), 3), round(float(r["longitude_deg"]), 3),
                         r["iso_country"], r["municipality"], r["iata_code"], r["type"]])
    out = ROOT / "web" / "data" / "places" / "airports.js"
    out.write_text("/* Generated by tools/build_places.py from data/sources/ourairports/airports-slice.csv (OurAirports, public domain).\n"
                   "   Columns: ident, name, lat, lon, country, municipality, iata, type. */\n"
                   "(window.SEAGLOBE_DATA = window.SEAGLOBE_DATA || {}).airports = " + json.dumps(rows, separators=(",", ":"), ensure_ascii=False) + ";\n")
    print(len(rows), "airports", out.stat().st_size // 1000, "kB")


if __name__ == "__main__":
    main()
