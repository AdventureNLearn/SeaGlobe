#!/usr/bin/env python3
"""Wrap selected three.js 0.187.0 example add-ons (MIT) as one classic script.

Reads examples/jsm files from an npm copy of three, rewrites `import {..} from 'three'`
into destructuring from window.SEAGLOBE_THREE, drops relative imports (the files share
one scope, in dependency order) and the `export` keywords. Output:
web/vendor/three-addons.global.js, which sets window.SEAGLOBE_THREE_ADDONS.
Usage: python3 tools/vendor_three_addons.py <path-to-node_modules/three>
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "web" / "vendor" / "three-addons.global.js"
FILES = [
    "postprocessing/Pass.js",
    "shaders/CopyShader.js",
    "shaders/LuminosityHighPassShader.js",
    "shaders/OutputShader.js",
    "postprocessing/UnrealBloomPass.js",
    "postprocessing/OutputPass.js",
    "objects/Lensflare.js",
]
EXPORTS = ["Pass", "FullScreenQuad", "CopyShader", "LuminosityHighPassShader", "OutputShader", "UnrealBloomPass", "OutputPass", "Lensflare", "LensflareElement"]


def main():
    base = Path(sys.argv[1]) / "examples" / "jsm"
    three_names = set()
    bodies = []
    for f in FILES:
        src = (base / f).read_text(encoding="utf-8")
        for m in re.finditer(r"import\s*\{([^}]*)\}\s*from\s*['\"]three['\"];", src, re.S):
            for part in m.group(1).split(","):
                part = part.strip()
                if part:
                    three_names.add(part.split(" as ")[0].strip())
        src = re.sub(r"import\s*\{[^}]*\}\s*from\s*['\"][^'\"]+['\"];", "", src, flags=re.S)
        src = re.sub(r"^export\s+\{[^}]*\};?\s*$", "", src, flags=re.M)
        src = re.sub(r"^export\s+(class|const|function|let)\s", r"\1 ", src, flags=re.M)
        if "import " in src.split("\n", 3)[0] or re.search(r"^\s*import\s", src, re.M):
            raise SystemExit("unhandled import in " + f)
        bodies.append(f"// ---- examples/jsm/{f} ----\n" + src)
    out = (
        "/* three.js r187 example add-ons (MIT License, Copyright 2010-2026 Three.js Authors):\n   "
        + ", ".join(FILES) + ".\n   Generated by tools/vendor_three_addons.py. Sets window.SEAGLOBE_THREE_ADDONS. */\n"
        "(function (root) {\n'use strict';\n"
        "const { " + ", ".join(sorted(three_names)) + " } = root.SEAGLOBE_THREE;\n"
        + "\n".join(bodies)
        + "\nroot.SEAGLOBE_THREE_ADDONS = { " + ", ".join(EXPORTS) + " };\n"
        "})(typeof window !== 'undefined' ? window : globalThis);\n"
    )
    OUT.write_text(out, encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT), len(out))


if __name__ == "__main__":
    main()
