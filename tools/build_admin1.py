"""Fill admin-1 state/province packs for every country on the globe.

The nine packs already built from Natural Earth 1:50m (USA, Canada, Australia,
Brazil, China, India, Indonesia, Russia, South Africa) are left as they are.
Every other country in the world pack is built from Natural Earth 1:10m
admin-1 (public domain), simplified for the globe and the lite size limit.

Usage:
  python3 tools/build_admin1.py /path/to/ne_10m_admin_1_states_provinces.shp

Source: Natural Earth 1:10m cultural, https://www.naturalearthdata.com/
  (naciscdn.org/naturalearth/10m/cultural/ne_10m_admin_1_states_provinces.zip).
"""
from __future__ import annotations

import json, pathlib, re, sys
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "web" / "data" / "regions"
KEEP = {"USA", "CAN", "AUS", "BRA", "CHN", "IND", "IDN", "RUS", "ZAF"}
# Target a few kilometres of detail: enough on the globe, small enough for lite.
TOL = 0.02
ND = 2
SRC = "Natural Earth (public domain), naturalearthdata.com"

# 162 individual packs + rest = 163 admin-1 files, leaving 10 lite slots (590).
# The smallest countries share admin1/rest.js (at least 15 of them).
REST_MIN = 15


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", str(s or "").lower()).strip("-") or "unit"


def load_js(path):
    t = path.read_text(encoding="utf-8")
    return json.loads(re.search(r"= (\{.*\});\s*$", t, re.S).group(1))


def write(key, obj):
    path = OUT / (key + ".js")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "/* Generated by tools/build_admin1.py from Natural Earth (public domain). Do not edit by hand. */\n"
        "(window.SEAGLOBE_REGIONS = window.SEAGLOBE_REGIONS || {})[" + json.dumps(key) + "] = "
        + json.dumps(obj, separators=(",", ":"), ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    return path.stat().st_size


def dedupe(ring):
    out = []
    for p in ring:
        q = [p[0], p[1]]
        if not out or out[-1] != q:
            out.append(q)
    return out


def rings_of(geom, nd=ND, tol=TOL):
    from shapely import set_precision
    if geom is None or geom.is_empty:
        return []
    g = geom.simplify(tol, preserve_topology=True) if tol else geom
    if g.is_empty:
        return []
    # Snap to the rounded grid and repair self-intersections from rounding.
    g = set_precision(g, 10 ** (-nd), mode="valid_output")
    if g.is_empty:
        return []

    def poly_rings(p):
        ext = dedupe([[round(x, nd), round(y, nd)] for x, y in p.exterior.coords])
        if len(ext) < 4:
            return []
        rings = [ext]
        for h in p.interiors:
            hr = dedupe([[round(x, nd), round(y, nd)] for x, y in h.coords])
            if len(hr) >= 4:
                rings.append(hr)
        return [rings]

    if g.geom_type == "Polygon":
        return poly_rings(g)
    if g.geom_type == "MultiPolygon":
        out = []
        for p in g.geoms:
            out.extend(poly_rings(p))
        return out
    if g.geom_type == "GeometryCollection":
        out = []
        for p in g.geoms:
            out.extend(rings_of(p, nd=nd, tol=0))
        return out
    return []


def bbox(polys):
    xs = [p[0] for poly in polys for r in poly for p in r]
    ys = [p[1] for poly in polys for r in poly for p in r]
    return [round(min(xs), 2), round(min(ys), 2), round(max(xs), 2), round(max(ys), 2)] if xs else None


def as_geom(sh):
    from shapely.geometry import shape
    from shapely.validation import make_valid
    g = shape(sh.__geo_interface__)
    if not g.is_valid:
        g = make_valid(g)
    return g


def union_of(items):
    from shapely.ops import unary_union
    geoms = []
    for it in items:
        g = as_geom(it["_shape"])
        if not g.is_empty:
            geoms.append(g)
    if not geoms:
        return None
    u = unary_union(geoms)
    if u.geom_type == "GeometryCollection":
        u = unary_union([p for p in u.geoms if p.geom_type in ("Polygon", "MultiPolygon")])
    return u


def pick_items(rows_by_a3):
    """Keep every Natural Earth row for a country, one per adm1_code."""
    selected = {}
    for a3, items in rows_by_a3.items():
        seen = {}
        for it in items:
            key = it.get("adm1_code")
            if key not in seen:
                seen[key] = it
        selected[a3] = list(seen.values())
    return selected


def features_for(a3, items):
    """Return a list of state dicts ready to write (no parent/bbox; those go in the index)."""
    items = relabel_proven_units(a3, items)
    used = set()
    out = []
    if a3 == "GBR":
        groups = defaultdict(list)
        for it in items:
            groups[it.get("geonunit") or it["name"]].append(it)
        for name, its in groups.items():
            g = union_of(its)
            polys = rings_of(g)
            if not polys:
                continue
            iso = {"England": "GB-ENG", "Scotland": "GB-SCT", "Wales": "GB-WLS",
                   "Northern Ireland": "GB-NIR"}.get(name)
            rec = make_state(name, iso, its[0].get("adm1_code"), "Constituent country", None, polys, used)
            out.append(rec)
        return out
    for it in items:
        g = as_geom(it["_shape"])
        polys = rings_of(g)
        if not polys:
            # A few islets collapse at 2 decimals; keep a 0.01° square so the source row is not dropped.
            c = g.centroid
            x, y = round(float(c.x), ND), round(float(c.y), ND)
            polys = [[[[x, y], [x + 10**(-ND), y], [x + 10**(-ND), y + 10**(-ND)], [x, y + 10**(-ND)], [x, y]]]]
        rec = make_state(it.get("name") or it.get("adm1_code"), it.get("iso_3166_2"),
                         it.get("adm1_code"), it.get("type_en") or None, it.get("postal") or None, polys, used)
        out.append(rec)
    return drop_unproven_duplicates(a3, out)


def _area(rec):
    a = 0
    for poly in rec.get("polys") or []:
        ring = poly[0]
        for i in range(len(ring) - 1):
            a += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1]
    return abs(a) / 2


def repair_utf8(s):
    """Undo the Latin-1/UTF-8 mojibake present in some Natural Earth text fields."""
    if not s:
        return s
    try:
        return s.encode("latin-1").decode("utf-8")
    except (UnicodeEncodeError, UnicodeDecodeError):
        return s


def relabel_proven_units(a3, items):
    """Correct labels using identifying fields already on the Natural Earth row.

    Croatia's HRV-1604 row copies iso_3166_2 HR-12 and name Brodsko-Posavska
    from the real HR-12 unit. The same row identifies it as Požeško-slavonska
    (ISO 3166-2:HR-11) via name_en, wikidataid Q58111, fips HR11, gns_adm1
    HR11, gns_name, hasc_maybe HR.PS, and woe_label. The geometry is kept.
    The name is taken from woe_label after repairing its UTF-8 storage.
    """
    if a3 != "HRV":
        return items
    out = []
    for it in items:
        fips = str(it.get("fips") or "").upper()
        gns = str(it.get("gns_adm1") or "").upper()
        name_en = it.get("name_en") or ""
        wid = it.get("wikidataid") or ""
        if (it.get("adm1_code") == "HRV-1604"
                or (fips == "HR11" and gns == "HR11"
                    and name_en.startswith("Požega-Slavonia") and wid == "Q58111")):
            it = dict(it)
            it["iso_3166_2"] = "HR-11"
            label = repair_utf8(it.get("woe_label") or "").split(",")[0].strip()
            it["name"] = label or name_en
            if str(it.get("hasc_maybe") or "").endswith(".PS"):
                it["postal"] = "PS"
        out.append(it)
    return out


def drop_unproven_duplicates(a3, recs):
    """Drop source rows that repeat a code without proving a new unit.

    Slovenia has a near-zero-area second SI-054; it is dropped, not relabelled.
    Croatia's second HR-12 row is relabelled to HR-11 first (see
    relabel_proven_units) when the same row proves that identity.
    """
    kept, seen_hr12 = [], False
    for rec in recs:
        iso, name = rec.get("iso"), rec.get("name")
        if a3 == "HRV" and iso == "HR-12" and name == "Brodsko-Posavska":
            if seen_hr12:
                continue
            seen_hr12 = True
        if a3 == "SVN" and iso == "SI-054" and _area(rec) < 1e-3:
            continue
        kept.append(rec)
    return kept


def make_state(name, iso, adm1_code, typ, postal, polys, used):
    iso_s = (iso or "").strip()
    if not iso_s or iso_s in {"-99", "-1", "NA"}:
        iso_s = None
    rid = "state-" + slug(iso_s or adm1_code or name)
    if rid in used:
        rid = "state-" + slug((iso_s or "") + "-" + (adm1_code or name))
    used.add(rid)
    rec = {"id": rid, "name": name, "iso": iso_s, "polys": polys}
    rec["_meta"] = {"type": typ, "postal": postal, "bbox": bbox(polys)}
    return rec


def patch_regions_js(rest_a3):
    path = ROOT / "web" / "js" / "regions.js"
    t = path.read_text(encoding="utf-8")
    block = ("  // <admin1-rest>\n"
             "  const ADMIN1_REST = new Set(" + json.dumps(sorted(rest_a3), separators=(",", ":")) + ");\n"
             "  // </admin1-rest>\n")
    if "// <admin1-rest>" in t:
        t = re.sub(r"  // <admin1-rest>\n.*?  // </admin1-rest>\n", block, t, count=1, flags=re.S)
    else:
        t = t.replace("  const HAS_ADMIN1 = new Set([\"USA\", \"CAN\", \"AUS\", \"BRA\", \"CHN\", \"IND\", \"IDN\", \"RUS\", \"ZAF\"]);\n", block)
    # pack path and coverage; drop HAS_ADMIN1 uses
    t = t.replace(
        'coverage: "Countries with Natural Earth 1:50m states/provinces (USA, Canada, Australia, Brazil, China, India, Indonesia, Russia, South Africa)"',
        'coverage: "Natural Earth states and provinces for every country"',
    )
    t = t.replace(
        "pack: (c) => c.country && HAS_ADMIN1.has(c.country.a3) ? \"admin1/\" + c.country.a3 : null",
        "pack: (c) => c.country ? (ADMIN1_REST.has(c.country.a3) ? \"admin1/rest\" : \"admin1/\" + c.country.a3) : null",
    )
    t = t.replace(
        "const statePack = ctx.country && alt < 1.3 && HAS_ADMIN1.has(ctx.country.a3) ? await loadPack(\"admin1/\" + ctx.country.a3) : null;",
        "const stateRaw = ctx.country && alt < 1.3 ? await loadPack(REGISTRY[1].pack(ctx)) : null;\n"
        "    const statePack = statesOf(stateRaw, ctx.country && ctx.country.a3);",
    )
    if "function statesOf(" not in t:
        t = t.replace(
            "  function loadPack(key) {",
            "  function statesOf(pack, a3) {\n"
            "    if (!pack) return null;\n"
            "    if (pack.states) return pack;\n"
            "    const one = pack.countries && a3 && pack.countries[a3];\n"
            "    return one && one.states ? one : null;\n"
            "  }\n"
            "  function loadPack(key) {",
        )
    path.write_text(t, encoding="utf-8")


def main(shp):
    import shapefile
    shp = pathlib.Path(shp)
    world = load_js(OUT / "world.js")
    world_a3 = {c["a3"] for c in world["countries"]}
    sf = shapefile.Reader(str(shp))
    fields = [f[0] for f in sf.fields[1:]]
    rows = defaultdict(list)
    for sr in sf.iterShapeRecords():
        d = dict(zip(fields, sr.record))
        d["_shape"] = sr.shape
        rows[d["adm0_a3"]].append(d)
    selected = pick_items(rows)

    built = {}
    for a3 in sorted(world_a3):
        if a3 in KEEP:
            continue
        items = selected.get(a3) or []
        states = features_for(a3, items)
        if not states:
            print("warning: no polygons for", a3, file=sys.stderr)
            continue
        built[a3] = states

    # smallest countries share rest.js so the lite file count stays under 600
    by_n = sorted(built.items(), key=lambda kv: (len(kv[1]), kv[0]))
    rest_n = max(REST_MIN, len(built) + len(KEEP) - 162)  # 162 individual + rest <= 163
    rest_a3 = [a3 for a3, _ in by_n[:rest_n]]
    rest_set = set(rest_a3)

    sizes = {}
    index_add = []
    feat_n = 0
    for a3, states in built.items():
        recs = []
        for s in states:
            meta = s.pop("_meta")
            recs.append(s)
            index_add.append({
                "id": s["id"], "level": "state", "name": s["name"], "type": meta["type"],
                "iso": s["iso"], "postal": meta["postal"], "parent": "country-" + a3.lower(),
                "bbox": meta["bbox"],
            })
            feat_n += 1
        if a3 not in rest_set:
            sizes["admin1/" + a3] = write("admin1/" + a3, {"country": a3, "states": recs})

    if rest_set:
        countries = {}
        for a3 in sorted(rest_set):
            countries[a3] = {"country": a3, "states": [s for s in built[a3]]}
        sizes["admin1/rest"] = write("admin1/rest", {"countries": countries})
        # drop any leftover individual pack for a country now in rest
        for a3 in rest_set:
            leftover = OUT / "admin1" / (a3 + ".js")
            if leftover.exists():
                leftover.unlink()

    # index: drop leftover generated state rows for non-KEEP countries, keep the 50m nine
    idx_path = OUT / "index.js"
    index = load_js(idx_path)
    keep_parents = {"country-" + a.lower() for a in KEEP}
    index["regions"] = [r for r in index["regions"] if not (r.get("level") == "state" and r.get("parent") not in keep_parents)]
    # also drop any previous rest/new packs from packs list; 50m nine stay
    keep_packs = {p for p in index.get("packs", []) if not str(p).startswith("admin1/") or str(p) in {"admin1/" + a for a in KEEP}}
    keep_packs |= set(sizes)
    index["packs"] = sorted(keep_packs)
    index["regions"].extend(index_add)
    index["source"] = SRC
    sizes["index"] = write("index", index)

    patch_regions_js(rest_set)

    kept_files = list((OUT / "admin1").glob("*.js"))
    kept_bytes = sum(p.stat().st_size for p in kept_files)
    new_bytes = sum(v for k, v in sizes.items() if k.startswith("admin1/"))
    print("countries", len(KEEP) + len(built),
          f"(kept 50m {len(KEEP)}, new 10m {len(built)}, rest {len(rest_set)})")
    print("features", 294 + feat_n, f"(kept 294 + new {feat_n})")
    print("admin1 files", len(list((OUT / "admin1").glob("*.js"))),
          f"bytes {kept_bytes} ({kept_bytes/1e6:.2f} MB)")
    print("wrote", ", ".join(f"{k} {v/1e3:.0f} kB" for k, v in sorted(sizes.items(), key=lambda kv: -kv[1])[:6]))
    print("rest", ",".join(sorted(rest_set)))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: python3 tools/build_admin1.py <ne_10m_admin_1_states_provinces.shp>")
    main(sys.argv[1])
