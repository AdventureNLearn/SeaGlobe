#!/usr/bin/env python3
"""Make the edition entry pages from web/index.html so they never drift:
   web/lite.html  - lite edition (Grok.me and small hosts): edition-lite.js, no bring-your-own pieces
   web/byo.html   - PC edition with bring-your-own live feeds: edition-byo.js, satellite.js and js/byo.js
   (byo.html is for this computer only; it is left out of GitHub Pages and the Grok.me lite build.)"""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = os.path.join(ROOT, "web")
EDITION = '  <script src="data/edition.js"></script>\n'
MARK = "  <!--BYO-->\n"

def csp(byo=False):
    c = json.load(open(os.path.join(ROOT, "data", "csp.json")))["hosts"]
    extra = json.load(open(os.path.join(ROOT, "data", "csp.json")))["byo_extra_connect"] if byo else []
    loc = c["local_tests"]
    connect = ["'self'", "data:", "blob:"] + c["version"] + c["tigerweb"] + c["chat"] + loc + extra
    parts = [
        "default-src 'self'",
        "script-src 'self' " + " ".join(c["radio_api_script"] + loc),
        "style-src 'self' 'unsafe-inline'",
        "img-src 'self' data: blob: " + " ".join(c["r2"] + loc),
        "media-src 'self' blob: " + " ".join(c["r2"] + loc),
        "font-src 'self'",
        "connect-src " + " ".join(dict.fromkeys(connect)),
        "frame-src " + " ".join(c["radio_player"]),
        "worker-src 'self' blob:",
        "object-src 'none'",
        "base-uri 'self'",
        "form-action 'none'",
    ]
    return '  <meta http-equiv="Content-Security-Policy" content="' + "; ".join(p.strip() for p in parts) + '">\n'

META = re.compile(r'  <meta http-equiv="Content-Security-Policy"[^>]*>\n')

def with_csp(text, byo=False):
    text = META.sub("", text)
    return text.replace('  <meta charset="utf-8">\n', '  <meta charset="utf-8">\n' + csp(byo), 1)

def make(check=False):
    ip = os.path.join(W, "index.html")
    src = with_csp(open(ip).read())
    if check and open(ip).read() != src:
        print("index.html CSP out of date - run tools/make_editions.py", file=sys.stderr); sys.exit(1)
    if not check:
        open(ip, "w").write(src)
    assert EDITION in src and MARK in src, "index.html lost its edition or BYO marker"
    head = "<!-- Generated by tools/make_editions.py from index.html. Do not edit by hand. -->\n"
    lite = src.replace(EDITION, '  <script src="data/edition-lite.js"></script>\n' + EDITION).replace(MARK, "")
    lite = lite.replace("<title>SeaGlobe — ", "<title>SeaGlobe Lite — ")
    byo = with_csp(src, True).replace(EDITION, '  <script src="data/edition-byo.js"></script>\n' + EDITION).replace(MARK, '  <script src="vendor/satellite.min.js"></script>\n  <script src="js/byo.js"></script>\n')
    byo = byo.replace("<title>SeaGlobe — ", "<title>SeaGlobe PC (your own feeds) — ")
    out = {"lite.html": lite.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + head, 1), "byo.html": byo.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + head, 1)}
    bad = []
    for name, text in out.items():
        p = os.path.join(W, name)
        if check:
            if not os.path.exists(p) or open(p).read() != text: bad.append(name)
        else:
            open(p, "w").write(text)
    if bad:
        print("out of date:", ", ".join(bad), "- run tools/make_editions.py", file=sys.stderr); sys.exit(1)
    print("editions", "checked" if check else "written")

if __name__ == "__main__":
    make("--check" in sys.argv)
