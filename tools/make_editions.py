#!/usr/bin/env python3
"""Make the edition entry pages from web/index.html so they never drift:
   web/lite.html  - lite edition (Grok.me and small hosts): edition-lite.js, no bring-your-own pieces
   web/byo.html   - PC edition with bring-your-own live feeds: edition-byo.js, satellite.js and js/byo.js
   (byo.html is for this computer only; it is left out of GitHub Pages and the Grok.me lite build.)"""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = os.path.join(ROOT, "web")
EDITION = '  <script src="data/edition.js"></script>\n'
MARK = "  <!--BYO-->\n"

def policy(extra_connect=(), test=False, r2=True):
    """The policy as a list of directives. test=True adds the local test hosts (only test servers ever do that)."""
    cfg = json.load(open(os.path.join(ROOT, "data", "csp.json")))
    c, loc = dict(cfg["hosts"]), (cfg["test_hosts"] if test else [])
    if not r2: c["r2"] = []   # the lite edition uses no asset host
    connect = ["'self'", "data:", "blob:"] + c["version"] + c["tigerweb"] + c["chat"] + c["r2"] + loc + list(extra_connect)
    return [
        "default-src 'self'",
        "script-src " + " ".join(["'self'"] + c["radio_api_script"] + loc),
        "style-src " + " ".join(["'self'"] + cfg["style_hashes"]),
        "img-src " + " ".join(["'self'", "data:", "blob:"] + c["r2"] + loc),
        "media-src " + " ".join(["'self'", "blob:"] + c["r2"] + loc),
        "font-src 'self'",
        "connect-src " + " ".join(dict.fromkeys(connect)),
        "frame-src " + " ".join(c["radio_player"]),
        "worker-src 'self' blob:",
        "object-src 'none'",
        "base-uri 'self'",
        "form-action 'none'",
    ]

def csp(r2=True):
    return '  <meta http-equiv="Content-Security-Policy" content="' + "; ".join(policy(r2=r2)) + '">\n'

META = re.compile(r'  <meta http-equiv="Content-Security-Policy"[^>]*>\n')
BYO_CSP = '  <script src="js/byo-csp.js"></script>\n'

def with_csp(text, byo=False):
    text = META.sub("", text).replace(BYO_CSP, "")
    return text.replace('  <meta charset="utf-8">\n', '  <meta charset="utf-8">\n' + (BYO_CSP if byo else csp()), 1)

def byo_csp_js():
    cfg = json.load(open(os.path.join(ROOT, "data", "csp.json")))
    base = policy(cfg["byo_local_connect"])
    return ("/* Generated by tools/make_editions.py from data/csp.json. Do not edit by hand.\n"
            "   PC edition only: writes this page's Content-Security-Policy before anything else loads. connect-src is the\n"
            "   published list plus this computer (127.0.0.1) and the exact origins of the feed URLs saved on this computer. */\n"
            "(function () {\n  \"use strict\";\n"
            "  var base = " + json.dumps(base) + ";\n"
            "  var extra = [];\n"
            "  [\"sg-byo-air\", \"sg-byo-tle-url\"].forEach(function (k) {\n"
            "    try { var u = new URL(localStorage.getItem(k) || \"\"); if (/^https?:$/.test(u.protocol)) extra.push(u.origin); } catch (e) { /* not set */ }\n"
            "  });\n"
            "  window.SEAGLOBE_BYO_ORIGINS = extra.slice();\n"
            "  var p = base.map(function (d) { return /^connect-src /.test(d) && extra.length ? d + \" \" + extra.join(\" \") : d; }).join(\"; \");\n"
            "  var m = document.createElement(\"meta\"); m.httpEquiv = \"Content-Security-Policy\"; m.content = p;\n"
            "  document.head.appendChild(m);\n})();\n")

def make(check=False):
    ip = os.path.join(W, "index.html")
    src = with_csp(open(ip).read())
    if check and open(ip).read() != src:
        print("index.html CSP out of date - run tools/make_editions.py", file=sys.stderr); sys.exit(1)
    if not check:
        open(ip, "w").write(src)
    assert EDITION in src and MARK in src, "index.html lost its edition or BYO marker"
    head = "<!-- Generated by tools/make_editions.py from index.html. Do not edit by hand. -->\n"
    lite = META.sub(csp(r2=False), src, count=1).replace(EDITION, '  <script src="data/edition-lite.js"></script>\n' + EDITION).replace(MARK, "")
    lite = lite.replace("<title>SeaGlobe — ", "<title>SeaGlobe Lite — ")
    byo = with_csp(src, True).replace(EDITION, '  <script src="data/edition-byo.js"></script>\n' + EDITION).replace(MARK, '  <script src="vendor/satellite.min.js"></script>\n  <script src="js/byo.js"></script>\n')
    byo = byo.replace("<title>SeaGlobe — ", "<title>SeaGlobe PC (your own feeds) — ")
    out = {"lite.html": lite.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + head, 1), "byo.html": byo.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + head, 1),
           os.path.join("js", "byo-csp.js"): byo_csp_js()}
    bad = []
    for name, text in out.items():
        p = os.path.join(W, name)
        if check:
            if not os.path.exists(p) or open(p).read() != text: bad.append(name)
        else:
            open(p, "w").write(text)
    if bad:
        print("out of date:", ", ".join(bad), "- run tools/make_editions.py", file=sys.stderr); sys.exit(1)
    print("editions", "checked" if check else "written")

if __name__ == "__main__":
    make("--check" in sys.argv)
